import time
# time モジュールを使うために必要。
#
# Work4 では、商品を順番に表示する間に
# 1秒待つ処理 time.sleep(1) を使っていた。
# そのため、今回もそのまま使えるように最初で import しておく。


# 合計金額を入れるための変数。
# 最初はまだ何も買っていないので 0 円。
total = 0


def buy_pork():
    # この関数は「豚肉を買う処理」だけを担当する。
    print('豚肉200円です。')

    # total は関数の外にある変数なので、
    # 関数の中で更新したいときは global total が必要。
    global total

    # 合計金額に 200 円を足す。
    total += 200


def buy_carrot():
    # この関数は「にんじんを買う処理」だけを担当する。
    print('にんじん120円です。')

    # 外の total を更新するために必要。
    global total

    # 合計金額に 120 円を足す。
    total += 120


def buy_potato():
    # この関数は「じゃがいもを買う処理」だけを担当する。
    print('じゃがいも180円です。')

    # 外の total を更新するために必要。
    global total

    # 合計金額に 180 円を足す。
    total += 180


def buy_onion():
    # この関数は「玉ねぎを買う処理」だけを担当する。
    print('玉ねぎ140円です。')

    # 外の total を更新するために必要。
    global total

    # 合計金額に 140 円を足す。
    total += 140


# ここから下は、作った関数を順番に実行している部分。
#
# 上で関数を定義しただけでは、まだ何も動かない。
# 「実行する」と書いて初めて、中の処理が動く。
buy_pork()
time.sleep(1)

buy_carrot()
time.sleep(1)

buy_potato()
time.sleep(1)

buy_onion()
time.sleep(1)


# ここから Work5 の追加部分。
# ----------------------------------------
# 目的：
# 「合計金額 total に対して、いくら支払うか」を入力してもらい、
# ちょうど・おつりあり・不足 の3パターンに分けて表示する。
# ----------------------------------------


# はらう金額を入力してもらう。
#
# input() で受け取る値は、見た目が数字でも文字列になる。
# たとえば 1000 と入力しても、この時点では数値ではなく "1000" という文字。
pay = input('¥')

# 支払い金額を整数に変換する。
#
# このあとで total と大小比較をしたいので、
# 数字として扱えるように int() で変換する。
pay = int(pay)


# おつりがいるかどうかを分岐する。
#
# 比べているものは、
# pay   = お客さんが払った金額
# total客さんが払った金額
# total = 商品の合計金額
#
# この2つを比べることで、
# 1. ちょうど払った
# 2. 多く払ったのでおつりがある
# 3. 足りない
# を判定できる。

if pay == total:
    # 支払い金額と合計金額が同じとき。
    # おつりも不足もないので、「ちょうどいただきます」と表示する。
    print(f'{total}円ちょうどいただきます。')

elif pay > total:
    # 支払い金額のほうが大きいとき。
    # この場合は、おつりが必要になる。
    #
    # おつりは
    # 払った金額 - 合計金額
    # で求められる。
    print(f'{pay - total}円のお返しです。')

else:
    # 上の2つに当てはまらないとき。
    # つまり、支払い金額が合計金額より少ないとき。
    #
    # 不足金額は
    # 合計金額 - 払った金額
    # で求められる。
    print(f'{total - pay}円不足しています。')