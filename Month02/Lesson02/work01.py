total = 0  # 合計金額を入れる変数。今は 0 円から始める。

def buy_pork():
    pork = 200  # 豚肉の値段を 200 円とする。
    print(f'豚肉{pork}円です。')  # 豚肉の値段を表示する。

    # ここが Work1 のいちばん大事なポイント。
    #
    # total += pork は、見た目は短く書いてあるが、
    # 意味としては次のような処理とほぼ同じ。
    #
    # total = total + pork
    #
    # すると Python は、
    # 「この関数の中で total に代入している」
    # と考える。
    #
    # つまり、関数の中の total は
    # 「この関数専用の変数」として扱われようとする。
    #
    # しかし右側の total + pork を計算する時点では、
    # その「関数の中の total」には、まだ値が入っていない。
    #
    # そのため、
    # 「使おうとしたが、まだ値が入っていない変数を読もうとした」
    # という状態になり、エラーになる。
    #
    # これが UnboundLocalError の正体。
    #
    # つまりこの Work1 では、
    # 「関数の中で外の変数をそのまま足そうとするとエラーになる」
    # という現象を確認するのが目的である。
    total += pork # type: ignore

buy_pork()  # 関数を実行する。

# この行は、本来は合計金額を表示するための行。
# ただし今回は buy_pork() の中でエラーが起きるため、
# ここまでは到達しない。
print(f'合計{total}円のお買い上げです。')