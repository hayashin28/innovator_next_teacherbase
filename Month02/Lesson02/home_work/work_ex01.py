import time
# time モジュールを使うために必要。
#
# ここでは time.sleep(1) を使って、
# 商品の表示と表示の間を 1 秒ずつ待たせる。
# そのため、プログラムの最初で import time を書いておく。


# 合計金額を入れるための変数。
# まだ何も買っていないので、最初は 0 円。
total = 0


def buy_pork():
    # この関数は「豚肉を買う処理」だけを担当する。
    print('豚肉200円です。')

    # total は関数の外にある変数なので、
    # 関数の中で値を増やしたいときは global total が必要。
    #
    # これを書かないと、
    # 関数の中で total を更新しようとしたときに
    # 「関数の中だけの total」と判断され、
    # Work1 / Work2 で確認したエラーの原因になる。
    global total

    # 合計金額に 200 円を足す。
    total += 200


def buy_carrot():
    # この関数は「にんじんを買う処理」だけを担当する。
    print('にんじん120円です。')

    # 外にある total を更新するために必要。
    global total

    # 合計金額に 120 円を足す。
    total += 120


def buy_potato():
    # この関数は「じゃがいもを買う処理」だけを担当する。
    print('じゃがいも180円です。')

    # 外にある total を更新するために必要。
    global total

    # 合計金額に 180 円を足す。
    total += 180


def buy_onion():
    # この関数は「玉ねぎを買う処理」だけを担当する。
    print('玉ねぎ140円です。')

    # 外にある total を更新するために必要。
    global total

    # 合計金額に 140 円を足す。
    total += 140


def payment(pay: int):
    # この関数は「支払い金額を見て、結果を表示する処理」だけを担当する。
    #
    # 引数 pay には、
    # ユーザーが支払う金額が入ってくる。
    #
    # 例：
    # payment(640)
    # と呼び出されたら、
    # pay の中には 640 が入る。
    #
    # ここで比べる相手は total。
    # total は関数の外で作られた合計金額である。
    #
    # 今回は total を「読むだけ」で、
    # 値を書き換えてはいない。
    # そのため、この関数では global total は不要。
    #
    # global が必要なのは、
    # 「外の変数を書き換えるとき」である。
    # 今回の payment() は total を見ているだけなので、書かなくてよい。

    # 支払い金額と合計金額が同じとき。
    # この場合は、おつりも不足もない。
    if pay == total:
        print(f'{total}円ちょうどいただきます。')

    # 支払い金額のほうが大きいとき。
    # この場合は、おつりが発生する。
    #
    # おつりは
    # 払った金額 - 合計金額
    # で求める。
    elif pay > total:
        print(f'{pay - total}円のお返しです。')

    # 上の2つに当てはまらないとき。
    # つまり、支払い金額のほうが少ないとき。
    #
    # 不足金額は
    # 合計金額 - 払った金額
    # で求める。
    else:
        print(f'{total - pay}円不足しています。')


# ここから下は、作った関数を順番に実行している部分。
#
# 上で def を使って関数を書いただけでは、
# まだ何も動かない。
# 「実行する」と書いて初めて、中の処理が動く。

buy_pork()
time.sleep(1)

buy_carrot()
time.sleep(1)

buy_potato()
time.sleep(1)

buy_onion()
time.sleep(1)


# ここで、ここまでの合計金額を表示する。
#
# スクショの実行イメージでは、
# 商品をすべて表示したあとに
# 「合計640円のお買い上げです」
# を先に出している。
#
# そのため、この行を payment() の前に置く。
print(f'合計{total}円のお買い上げです。')


# ユーザーに支払い金額を入力してもらう。
#
# input() で受け取る値は文字列になる。
# たとえば 640 と入力しても、この時点では "640" である。
pay = input('¥')

# 文字列のままだと金額比較に使いにくいので、
# int() で整数に変換する。
pay = int(pay)

# 支払い処理の関数を実行する。
# ここで、入力された pay を引数として渡している。
payment(pay)