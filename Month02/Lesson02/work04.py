import time
# time モジュールを使うために必要。
#
# Work4 では「1秒待つ」を入れたいので、
# time.sleep(1) を使えるように、最初に import time を書いておく。
#
# ここで大事なのは、
# import は「関数の中」ではなく「プログラムの最初」に書いておくこと。
# こうすると、この下にあるすべての処理で time が使えるようになる。


# 合計金額を入れるための変数。
# まだ何も買っていないので、最初は 0 円にしておく。
total = 0


def buy_pork():
    # この関数は「豚肉を買う処理」だけを担当する。
    #
    # Work3 のポイントは、
    # 1つの長い処理をまとめて書くのではなく、
    # 材料ごとに関数を分けていくこと。
    #
    # こうすると、
    # 「豚肉の処理」
    # 「にんじんの処理」
    # 「じゃがいもの処理」
    # 「玉ねぎの処理」
    # をそれぞれ独立して読めるようになる。
    print('豚肉200円です。')

    # global total を書くことで、
    # 「この関数の中で使う total は、関数の外にある total のことです」
    # と Python に伝えている。
    #
    # これを書かないと、
    # 関数の中で total を更新しようとしたときに、
    # 関数の中だけの total だと判断されてしまい、
    # Work2 までで確認した UnboundLocalError の原因になる。
    global total

    # 合計金額 total に、豚肉 200 円を足す。
    total += 200


def buy_carrot():
    # この関数は「にんじんを買う処理」だけを担当する。
    # buy_pork() と同じ形で書くことで、
    # 「材料が増えても、同じ書き方をくり返せばよい」
    # ということを見せている。
    print('にんじん120円です。')

    # total は関数の外にある合計金額なので、
    # ここでも global total が必要。
    global total

    # 合計金額に、にんじん 120 円を足す。
    total += 120


def buy_potato():
    # この関数は「じゃがいもを買う処理」だけを担当する。
    # 役割を材料ごとに分けることで、
    # どの関数が何をしているかが見やすくなる。
    print('じゃがいも180円です。')

    # 外の total を使うので global total を書く。
    global total

    # 合計金額に、じゃがいも 180 円を足す。
    total += 180


def buy_onion():
    # この関数は「玉ねぎを買う処理」だけを担当する。
    # Work3 では、こうして材料ごとの関数を増やしていく。
    print('玉ねぎ140円です。')

    # 外にある total を更新するために必要。
    global total

    # 合計金額に、玉ねぎ 140 円を足す。
    total += 140


# ここから下は、作った関数を順番に実行している部分。
#
# 上で関数を定義しただけでは、まだ何も動かない。
# 「実行する」と書いて初めて、中の処理が動く。
#
# 今回は、
# 1. 豚肉を買う
# 2. 1秒待つ
# 3. にんじんを買う
# 4. 1秒待つ
# 5. じゃがいもを買う
# 6. 1秒待つ
# 7. 玉ねぎを買う
# 8. 1秒待つ
# という順番で実行している。
#
# Work4 の新しいポイントは、
# 「待つ処理」は関数の中にまとめて入れたのではなく、
# 関数と関数のあいだに書いていること。
#
# つまり今回は、
# 「各商品の表示と表示の間を1秒あけたい」ので、
# buy_xxx() の実行と実行の間に time.sleep(1) を入れている。
#
# ここを理解できないと、
# 「なぜ関数の中ではなく外に sleep を書くのか」
# が分からなくなりやすい。
buy_pork()

# 1秒待つ。
#
# time.sleep(1) は「1秒間、次の処理へ進まない」という意味。
# これによって、すぐ次の材料が表示されず、
# 少し間をあけて順番に表示される。
time.sleep(1)

buy_carrot()

# にんじんの表示が終わったあと、次の表示まで1秒待つ。
time.sleep(1)

buy_potato()

# じゃがいもの表示が終わったあと、次の表示まで1秒待つ。
time.sleep(1)

buy_onion()

# 玉ねぎの表示が終わったあと、最後の合計表示へ進む前に1秒待つ。
#
# この1秒待ちを入れることで、
# 最後の材料表示の直後にすぐ合計が出るのではなく、
# 少し間を置いてから合計が表示される。
time.sleep(1)


# 最後に、関数の中で足し合わせてきた total を表示する。
#
# 計算の流れは次の通り。
# 最初: total = 0
# 豚肉: total = 0 + 200   → 200
# にんじん: total = 200 + 120 → 320
# じゃがいも: total = 320 + 180 → 500
# 玉ねぎ: total = 500 + 140 → 640
#
# そのため、ここでは
# 「合計640円のお買い上げです。」
# と表示される。
print(f'合計{total}円のお買い上げです。')