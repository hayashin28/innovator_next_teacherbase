import time

# 合計金額を覚えておくための変数。
# 最初はまだ商品を買っていないので、合計金額は 0 円から始める。
#
# この total は、ループの中で少しずつ増えていき、
# ループが終わったあとにも「最終的な合計金額」として使う。
total = 0

# 100円の商品を5つ買うので、同じ処理を5回くり返す。
#
# 今回は「何回目か」という値は使わないため、
# 使わない変数であることを示す _ を使っている。
for _ in range(5):

    # 今の合計金額 total に 100円を足す。
    #
    # total += 100 は、
    # total = total + 100
    # と同じ意味。
    #
    # 1回ごとに total の中身は、
    # 0 → 100 → 200 → 300 → 400 → 500
    # と変化していく。
    total += 100

    # レジで商品を1つずつ読み込むように、
    # 1回ごとに1秒待つ。
    #
    # 一気に全部表示するのではなく、
    # 「1つ買うごとに合計金額が増えている」
    # という流れを見せるための待ち時間。
    time.sleep(1)

    # 現在の合計金額を表示する。
    #
    # f"{total}円" と書くことで、
    # total の現在の値を文字列の中に埋め込める。
    #
    # ここでは、途中経過として
    # 100円、200円、300円、400円、500円
    # と表示している。
    print(f"{total}円")

# for文が終わったあとに、最後のお礼メッセージを表示する。
#
# ここで使っている total は、ループで増え終わったあとの値。
# つまり、最終的な合計金額である 500 が入っている。
#
# この行はループの外にあるため、5回くり返されるのではなく、
# 最後に1回だけ実行される。
#
# f-string を使うことで、
# 「合計500円」のように、計算結果を文章の中へ自然に入れられる。
print(f"ありがとうございます。合計{total}円のお買い上げです。")