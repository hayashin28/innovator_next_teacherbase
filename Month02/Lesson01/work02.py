import time

# 合計金額を覚えておくための変数。
# total は「計算に使う数値」として扱う。
# ここに "円" という文字は入れない。
#
# たとえば total = "0円" のようにしてしまうと、
# あとで total += 100 のような計算がしにくくなる。
# そのため、金額の本体は数値のまま持っておく。
total = 0

# 100円の商品を5つ買うので、同じ処理を5回くり返す。
# 今回も「何回目か」という値は使わないため、
# 使わない変数であることを示す _ を使っている。
for _ in range(5):

    # 今の合計金額に100円を足す。
    #
    # total += 100 は、
    # total = total + 100
    # と同じ意味。
    #
    # total の中身は、
    # 0 → 100 → 200 → 300 → 400 → 500
    # と、1回ごとに増えていく。
    total += 100

    # レジで商品を1つずつ読み込むように、
    # 1回ごとに1秒待つ。
    #
    # 数字が一瞬で全部出るのではなく、
    # 「商品を1つ買うたびに合計が増える」
    # という動きを見せるための待ち時間。
    time.sleep(1)

    # 現在の合計金額を「100円」のように表示する。
    #
    # f"{total}円" は f-string と呼ばれる書き方。
    # {} の中に変数 total を入れることで、
    # total の現在の値を文字列の中に埋め込める。
    #
    # 重要なのは、
    # total 自体は数値のままにしておき、
    # 表示するときだけ "円" をくっつけていること。
    #
    # これにより、
    # 計算しやすさと、見やすい表示を両立できる。
    print(f"{total}円")