import time

# 電子レンジの確認メッセージ。
# ここはカウントダウン処理の前に1回だけ表示する。
print("温めますか？")

# for文で5回くり返す。
#
# range(5) は、
# 0, 1, 2, 3, 4
# という5つの値を順番に i へ入れる。
#
# 今回のポイントは、この i をそのまま表示するのではなく、
# 5 - i と計算して、5, 4, 3, 2, 1 に変えること。
for i in range(5):

    # i の値は 0 から始まる。
    #
    # i = 0 のとき 5 - i は 5
    # i = 1 のとき 5 - i は 4
    # i = 2 のとき 5 - i は 3
    # i = 3 のとき 5 - i は 2
    # i = 4 のとき 5 - i は 1
    #
    # このように、増えていく i を使って、
    # 逆に減っていく数を作っている。
    print(5 - i)

    # 1つ数字を表示したあと、1秒待つ。
    #
    # これにより、
    # 5 → 1秒待つ → 4 → 1秒待つ → 3 ...
    # というカウントダウンらしい動きになる。
    time.sleep(1)

# for文が終わったあとに1回だけ表示する。
#
# この行はループの外にあるため、
# カウントダウンが全部終わってから実行される。
print("チン！")


