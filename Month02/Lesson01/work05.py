import time

# 電子レンジを使う前の確認メッセージ。
# カウントダウンが始まる前に、1回だけ表示する。
print("温めますか？")

# 5秒カウントダウンするために、同じ処理を5回くり返す。
#
# range(5) は、
# 0, 1, 2, 3, 4
# という値を順番に i へ入れる。
#
# i 自体は 0 から 4 へ増えていくが、
# 表示したいのは 5, 4, 3, 2, 1 という減っていく数。
# そのため、5 - i という計算を使う。
for i in range(5):

    # 1秒待つ。
    #
    # これにより、電子レンジの残り時間が
    # 1秒ごとに減っていくような動きになる。
    #
    # ※最初の「5秒」をすぐ表示したい場合は、
    #   print() のあとに time.sleep(1) を置いてもよい。
    time.sleep(1)

    # 残り時間を「5秒」「4秒」のように表示する。
    #
    # 5 - i は数値の計算。
    # f"{5 - i}秒" は、その計算結果に「秒」という文字を付けて、
    # 人間に分かりやすい表示へ変換している。
    #
    # i = 0 のとき 5 - i は 5 なので「5秒」
    # i = 1 のとき 5 - i は 4 なので「4秒」
    # i = 2 のとき 5 - i は 3 なので「3秒」
    # i = 3 のとき 5 - i は 2 なので「2秒」
    # i = 4 のとき 5 - i は 1 なので「1秒」
    # と表示される。
    print(f"{5 - i}秒")

# カウントダウンが終わったあと、少し間を置く。
# 「1秒」の表示直後にすぐ鳴るより、
# 電子レンジらしい間を作るための待ち時間。
time.sleep(1)

# カウントダウン終了後のメッセージ。
# この行は for文の外にあるため、最後に1回だけ実行される。
print("チン！")

# ここから先は、教材条件にはない追加演出。
# 基本課題の答えとは分けて、
# 余裕がある子向けの遊び・発展として扱うとよい。
time.sleep(3)
print("ドカン！！")