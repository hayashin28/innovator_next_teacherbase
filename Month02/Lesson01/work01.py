import time

# 合計金額を覚えておくための変数。
# 最初はまだ何も買っていないので、合計は 0 円から始める。
total = 0

# 100円の商品を5つ買うので、同じ処理を5回くり返す。
# 今回は「何回目か」という値そのものは使わないため、
# 使わない変数であることを示す慣習として _ を使っている。
for _ in range(5):

    # 今の合計金額 total に、100円を足す。
    #
    # total += 100 は、
    # total = total + 100
    # と同じ意味。
    #
    # つまり、
    # 「今の total を読み取る」
    # →「100 を足す」
    # →「計算結果をもう一度 total に入れ直す」
    # という処理になっている。
    #
    # ここがこの課題の中心。
    # total は毎回上書きされながら、
    # 100 → 200 → 300 → 400 → 500 と変化していく。
    total += 100

    # レジで商品を1つずつ読み込むように、
    # 1回ごとに少し待つ。
    #
    # これにより、画面に数字が一気に出るのではなく、
    # 「1つ買うごとに合計が増えている」ことを見せやすくなる。
    time.sleep(1)

    # 現在の合計金額を表示する。
    #
    # 1回目は 100
    # 2回目は 200
    # 3回目は 300
    # 4回目は 400
    # 5回目は 500
    # と表示される。
    print(total)