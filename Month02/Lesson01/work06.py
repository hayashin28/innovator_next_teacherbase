import time

# 何秒温めるかを、ユーザーに入力してもらう。
#
# input() で受け取った値は、見た目が数字でも「文字列」として扱われる。
# たとえば 5 と入力しても、この時点では数値の 5 ではなく、文字の "5" である。
num = input("何秒温めますか？：")

# 入力された文字列を、整数に変換する。
#
# range(num) のように、くり返し回数として使うためには、
# num が数値である必要がある。
#
# そのため、int(num) で文字列を整数へ変換している。
num = int(num)

# 入力された秒数だけ、カウントダウンをくり返す。
#
# たとえば num が 5 の場合、
# range(num) は 0, 1, 2, 3, 4 を順番に i へ入れる。
#
# i は増えていくが、表示したい残り時間は減っていくため、
# num - i を使っている。
for i in range(num):

    # 1秒待つ。
    #
    # 電子レンジの残り時間が、1秒ごとに減るように見せるための待ち時間。
    time.sleep(1)

    # 残り時間を表示する。
    #
    # num = 5 の場合、
    # i = 0 → 5 - 0 = 5
    # i = 1 → 5 - 1 = 4
    # i = 2 → 5 - 2 = 3
    # のように、5秒、4秒、3秒……と表示される。
    #
    # f-string を使うことで、計算結果に「秒」という文字を付けて表示できる。
    print(f"{num - i}秒")

# カウントダウンが終わったあとに、1回だけ表示する。
#
# この行は for文の外にあるため、くり返されず、最後に1回だけ実行される。
print("チン！")

# 入力された秒数を使って、完了メッセージを表示する。
#
# num には、最初に入力された秒数が整数として残っている。
# そのため、「5秒の温めが終わりました！」のように表示できる。
print(f"{num}秒の温めが終わりました！")

# ここから先は追加演出。
# 基本課題の条件には含まれないため、
# 余裕がある子向けの遊びとして扱う。
time.sleep(3)
print("ドカン！")