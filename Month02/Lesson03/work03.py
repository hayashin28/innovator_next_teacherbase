# お小遣いの残り金額を表す変数。
#
# pocket は「計算に使う金額」なので、2000 という数値で持つ。
# "2000円" のような文字列にしてしまうと、
# あとで焼きそば代を引き算できなくなる。
pocket = 2000

# 現在のお小遣いを表示する。
#
# pocket は数値として持ち、
# 表示するときだけ f-string で「円」を付ける。
# 「計算用の値」と「表示用の文字」を分けることが大切。
print(f"お小遣いは{pocket}円です。")


def yakisoba_shop():
    """
    焼きそばを買う処理をまとめた関数。

    このWorkの目的は、
    「入力された人数分の焼きそば代を計算し、
    お小遣い pocket から引く」
    という流れを作ること。

    ここで大事なのは、
    ・input() で買う数を受け取る
    ・int() で数値に変換する
    ・単価 × 個数 で合計金額を計算する
    ・pocket から合計金額を引く
    という処理の順番。

    なお、global は外側の変数を書き換える強い道具。
    今回は教材の意図に合わせて使うが、
    本来の設計では戻り値を使って新しい残金を返す方が安全な場面も多い。
    """

    # 関数の外で宣言された pocket を、
    # この関数の中から変更するための宣言。
    #
    # これを書かずに pocket -= total_price のようにすると、
    # Python は「関数の中だけの pocket を作ろうとしている」と解釈し、
    # エラーの原因になる。
    global pocket

    # 焼きそば1人前の値段。
    #
    # pocket -= 120 * count のように直接書くこともできるが、
    # yakisoba という名前を付けることで、
    # 「120 が焼きそば1人前の値段である」と意味が見える。
    yakisoba = 120

    # 焼きそばを何人前買うか、入力してもらう。
    #
    # input() で受け取った値は、見た目が数字でも文字列になる。
    # たとえば 3 と入力しても、この時点では "3" という文字。
    #
    # 焼きそば代の計算に使うため、int() で整数に変換する。
    count = int(input("焼きそばは何人前ですか？："))

    # 焼きそばの合計金額を計算する。
    #
    # 1人前120円を count 人前買うので、
    # 焼きそば代の合計は yakisoba * count になる。
    #
    # 例：
    # count が 3 の場合
    # 120 * 3 = 360
    #
    # ここで total_price という変数に入れておくことで、
    # 「支払う合計金額」を後の処理で使いやすくしている。
    total_price = yakisoba * count

    # 買った焼きそばの人数と、合計金額を表示する。
    #
    # f-string を使うことで、
    # count と total_price の値を文章の中に埋め込める。
    #
    # 出力例：
    # 焼きそばは3人前360円です。
    print(f"焼きそばは{count}人前{total_price}円です。")

    # お小遣いから、焼きそばの合計金額を引く。
    #
    # pocket -= total_price は、
    # pocket = pocket - total_price
    # と同じ意味。
    #
    # 例：
    # pocket が 2000
    # total_price が 360 の場合
    # pocket = 2000 - 360
    # となり、pocket は 1640 に更新される。
    #
    # ここで大切なのは、
    # pocket の中身が「新しい残金」に上書きされること。
    pocket -= total_price

    # 残りのお小遣いを表示する。
    #
    # 単一責任の原則で考えると、
    # 本来は「計算する関数」と「表示する処理」を分ける方がきれい。
    #
    # ただし、このWorkでは
    # 「関数の中で買い物処理を行い、その結果 pocket が減る」
    # ことを確認する目的があるため、教材準拠としてここで表示している。
    print(f"残りのお小遣いは{pocket}円です。")


# 関数を呼び出す。
#
# 関数は def で作っただけでは実行されない。
# この行で初めて、
# ・注文数の入力
# ・合計金額の計算
# ・お小遣いの更新
# ・残金表示
# が実行される。
yakisoba_shop()