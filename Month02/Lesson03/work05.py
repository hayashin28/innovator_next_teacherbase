import time


# お小遣いの残り金額を表す変数。
#
# pocket は「計算に使う金額」なので、2000 という数値で持つ。
# "2000円" のような文字列で持ってしまうと、
# あとで焼きそば代やお面代を引き算できなくなる。
pocket = 2000

# 現在のお小遣いを表示する。
#
# pocket は数値として持ち、
# 表示するときだけ f-string で「円」を付ける。
#
# 出力例：
# お小遣いは2000円です。
print(f"お小遣いは{pocket}円です。")


def yakisoba_shop():
    """
    焼きそば屋で買い物する関数。

    この関数の役割は、
    「焼きそばを何人前買うかを入力してもらい、
    その合計金額を pocket から引くこと」。

    ここでは、残りのお小遣いの表示は行わない。
    理由は、残金表示は「焼きそば屋だけの仕事」ではなく、
    買い物全体の流れを管理する側の仕事だから。

    たとえば、
    ・焼きそばを買った直後に残金を見せたい
    ・お面も買ったあとにまとめて残金を見せたい
    ・全部の屋台を回った最後にだけ残金を見せたい
    というように、表示のタイミングは外側で変えられる。

    関数の中に残金表示まで入れてしまうと、
    「買う処理」と「全体の表示タイミング」が混ざってしまう。
    """

    # 関数の外側にある pocket を、
    # この関数の中で変更するための宣言。
    #
    # 今回は、焼きそばを買った結果として
    # 外側の pocket の値そのものを減らしたい。
    #
    # global は便利だが、外側の値を直接変える強い道具。
    # 使いすぎると「どこで pocket が変わったのか」が追いにくくなる。
    # 今回は教材準拠として使っている。
    global pocket

    # 焼きそば1人前の値段。
    #
    # 直接 120 と書くのではなく yakisoba_price という変数名にすると、
    # 「この120は焼きそばの値段である」と意味が分かりやすくなる。
    yakisoba_price = 120

    # 注文入力の前に1秒待つ。
    #
    # 表示が一気に流れないようにし、
    # 屋台で注文しているような間を作るため。
    time.sleep(1)

    # 焼きそばを何人前買うか入力してもらう。
    #
    # input() の戻り値は文字列なので、
    # 計算に使うため int() で整数に変換する。
    count = int(input("焼きそばは何人前ですか？："))

    # 焼きそばの合計金額を計算する。
    #
    # 単価 × 個数 = 合計金額
    #
    # 例：
    # 120円 × 4人前 = 480円
    total_price = yakisoba_price * count

    # 注文結果を出す前に1秒待つ。
    #
    # 「注文を受けて、金額を確認している」ような間を作るため。
    time.sleep(1)

    # 焼きそばの注文内容と合計金額を表示する。
    #
    # f-string を使うことで、
    # count と total_price の値を文章に埋め込んでいる。
    print(f"焼きそばは{count}人前{total_price}円です。")

    # お小遣いから焼きそば代を引く。
    #
    # pocket -= total_price は、
    # pocket = pocket - total_price
    # と同じ意味。
    #
    # ここで pocket の中身が「買い物後の残金」に更新される。
    pocket -= total_price


def omen_shop():
    """
    お面屋で買い物する関数。

    この関数の役割は、
    「お面をいくつ買うかを入力してもらい、
    その合計金額を pocket から引くこと」。

    yakisoba_shop() と同じ形にすることで、
    商品が変わっても、
    ・値段を決める
    ・個数を入力する
    ・合計金額を計算する
    ・pocket から引く
    という共通の流れが見える。

    ここで大切なのは、
    関数名を ○○_shop でそろえること。
    関数名の形をそろえると、
    「これは屋台の処理だ」と読み取りやすくなる。
    """

    # 関数の外側にある pocket を変更するための宣言。
    #
    # 焼きそば屋と同じく、
    # お面を買った結果として pocket を減らしたいので global を使う。
    global pocket

    # お面1個の値段。
    #
    # 直接 100 と書くのではなく omen_price にしておくことで、
    # この金額が何の商品価格なのか分かりやすくなる。
    omen_price = 100

    # 入力前に1秒待つ。
    # 出力が一気に流れないよう、読みやすい間を作る。
    time.sleep(1)

    # お面をいくつ買うか入力してもらう。
    #
    # input() は文字列を返すため、
    # int() で整数に変換してから count に入れる。
    count = int(input("お面はいくつですか？："))

    # お面の合計金額を計算する。
    #
    # 単価 × 個数 = 合計金額
    #
    # 例：
    # 100円 × 3個 = 300円
    total_price = omen_price * count

    # 注文結果を出す前に1秒待つ。
    time.sleep(1)

    # お面の注文内容と合計金額を表示する。
    print(f"お面は{count}個{total_price}円です。")

    # お小遣いからお面代を引く。
    #
    # この処理により、pocket はさらに減る。
    #
    # 重要なのは、yakisoba_shop() で減った pocket を、
    # omen_shop() でも続けて使っていること。
    # つまり pocket は、買い物全体を通して共有される残金である。
    pocket -= total_price


# ここから下は、買い物全体の流れを管理する部分。
#
# どの屋台に行くか、
# どの順番で買うか、
# どのタイミングで残金を表示するか、
# それらは各 shop 関数ではなく、外側の処理が決める。
#
# これにより、
# 「屋台ごとの買い物処理」と
# 「買い物全体の進行」を分けて考えられる。


# まず焼きそば屋で買い物する。
yakisoba_shop()

# 焼きそばを買ったあとの残金を表示する。
#
# ここを yakisoba_shop() の中に入れない理由：
# yakisoba_shop() は焼きそばを買う処理だけを担当させたいから。
#
# 残金をいつ表示するかは、
# 買い物全体を管理する外側で決める。
print(f"残りのお小遣いは{pocket}円です。")

# お面屋で買い物する。
omen_shop()

# お面を買ったあとの残金を表示する。
#
# ここも omen_shop() の中には入れず、
# 外側で表示している。
#
# こうしておくと、あとで屋台が増えても、
# 「各 shop 関数は買い物処理」
# 「外側は全体の流れと表示タイミング」
# という役割分担を保ちやすい。
print(f"残りのお小遣いは{pocket}円です。")