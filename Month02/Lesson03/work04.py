import time


# お小遣いの残り金額を表す変数。
#
# pocket は「計算に使う金額」なので、2000 という数値で持つ。
# "2000円" のような文字列で持ってしまうと、
# あとで焼きそば代を引き算できなくなる。
pocket = 2000

# 現在のお小遣いを表示する。
#
# pocket は数値として持ち、
# 表示するときだけ f-string で「円」を付ける。
#
# 出力例：
# お小遣いは2000円です。
print(f"お小遣いは{pocket}円です。")


def yakisoba_shop():
    """
    焼きそばを買う処理をまとめた関数。

    このWorkの目的は、
    Work3の買い物処理に「1秒待つ」を追加して、
    出力結果を人間が読みやすいタイミングに整えること。

    ここで大切なのは、
    time.sleep(1) が「処理を1秒止める命令」であり、
    レジや屋台でやり取りしているような間を作れる、という点。

    また、print() だけを書くと空行を出せる。
    これにより、結果表示を見やすく区切ることができる。
    """

    # 関数の外側にある pocket を、
    # この関数の中で変更するための宣言。
    #
    # 今回は、焼きそばを買った結果として
    # 外側の pocket の値そのものを減らしたい。
    #
    # global を使うと外側の変数を直接書き換えられるが、
    # 使いすぎると「どこで値が変わったのか」が分かりにくくなる。
    # そのため、本来は注意して使う必要がある。
    global pocket

    # 焼きそば1人前の値段。
    #
    # 直接 120 と書くのではなく yakisoba という変数名を付けることで、
    # 「この120は焼きそばの値段である」と意味が分かりやすくなる。
    yakisoba = 120

    # すぐに入力へ進まず、1秒待つ。
    #
    # これにより、
    # 「お小遣いは2000円です。」
    # が表示されたあと、少し間を置いてから注文を聞ける。
    time.sleep(1)

    # 焼きそばを何人前買うか入力してもらう。
    #
    # input() の戻り値は文字列なので、
    # int() で整数に変換してから count に入れる。
    #
    # 例：
    # 3 と入力された場合、count には整数の 3 が入る。
    count = int(input("焼きそばは何人前ですか？："))

    # 焼きそばの合計金額を計算する。
    #
    # 1人前120円を count 人前買うので、
    # 合計金額は yakisoba * count になる。
    #
    # 例：
    # count が 3 の場合
    # 120 * 3 = 360
    total_price = yakisoba * count

    # 注文入力のあと、すぐ結果を出さずに1秒待つ。
    #
    # これは、屋台の人が注文を確認しているような間を作るため。
    time.sleep(1)

    # 買った焼きそばの人数と、合計金額を表示する。
    #
    # f-string を使うことで、
    # count と total_price の値を文章の中に埋め込める。
    #
    # 出力例：
    # 焼きそばは3人前360円です。
    print(f"焼きそばは{count}人前{total_price}円です。")

    # お小遣いから、焼きそばの合計金額を引く。
    #
    # pocket -= total_price は、
    # pocket = pocket - total_price
    # と同じ意味。
    #
    # 例：
    # pocket が 2000
    # total_price が 360 の場合
    # pocket = 2000 - 360
    # となり、pocket は 1640 に更新される。
    pocket -= total_price

    # 空行を出す。
    #
    # print() の中に何も書かないと、改行だけが出力される。
    # これにより、
    # 「焼きそばは3人前360円です。」
    # と
    # 「残りのお小遣いは1640円です。」
    # の間に空白ができ、結果が読みやすくなる。
    print()

    # 残金表示の前に1秒待つ。
    #
    # 出力を一気に出さず、読みやすいテンポにするため。
    time.sleep(1)

    # 残りのお小遣いを表示する。
    #
    # 注意：
    # 単一責任の原則で考えると、
    # 本来は「計算する関数」と「表示する処理」は分けた方がきれい。
    #
    # ただし、このWorkでは
    # 「関数の中で買い物処理を行い、結果を確認する」
    # ことが目的なので、教材準拠としてここで表示している。
    print(f"残りのお小遣いは{pocket}円です。")


# yakisoba_shop 関数を呼び出す。
#
# def で関数を作っただけでは、まだ処理は実行されない。
# この行で初めて、
# ・注文数の入力
# ・合計金額の計算
# ・お小遣いの更新
# ・残金表示
# が実行される。
yakisoba_shop()