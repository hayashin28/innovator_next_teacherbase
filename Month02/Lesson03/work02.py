# お小遣いの残り金額を表す変数。
#
# ここでは「2000円」という文字列ではなく、2000 という数値で持つ。
# 理由は、あとで焼きそばを買ったときに、
# pocket から yakisoba の金額を引き算するため。
#
# もし pocket = "2000円" のように文字列で持ってしまうと、
# pocket -= yakisoba のような計算ができなくなる。
pocket = 2000

# 現在のお小遣いを表示する。
#
# pocket は計算用の数値なので、表示するときだけ f-string で「円」を付ける。
# 「計算用の値」と「表示用の文字」を分けることが大切。
print(f"お小遣いは{pocket}円です。")


def yakisoba_shop():
    """
    焼きそばを1人前買う関数。

    この関数の教材上の目的は、
    「関数の外で作った変数 pocket を、関数の中から変更する」
    という動きを確認すること。

    ただし、global は強い道具なので乱用しない。
    本来の設計では、関数の中で外側の変数を直接書き換えるより、
    戻り値を使って新しい金額を返す方が安全で分かりやすい場合が多い。

    今回はロボ団テキストの学習意図に合わせて、
    global を使う形で書いている。
    """

    # 関数の外側にある pocket を、この関数の中で変更するための宣言。
    #
    # これを書かずに pocket -= yakisoba とすると、
    # Python は「関数の中だけで使う pocket を作ろうとしている」と解釈する。
    #
    # その結果、外側の pocket をうまく更新できず、エラーの原因になる。
    #
    # つまり global pocket は、
    # 「ここで使う pocket は、関数の外にある pocket です」
    # と Python に伝えるための宣言。
    global pocket

    # 焼きそば1人前の値段。
    #
    # 直接 pocket -= 120 と書くこともできるが、
    # yakisoba という変数名を付けることで、
    # 「120 が何の金額なのか」が分かりやすくなる。
    #
    # これは、後で値段を変更したいときにも便利。
    yakisoba = 120

    # 焼きそばの値段を表示する。
    #
    # ここでも yakisoba は数値として持ち、
    # 表示するときだけ「円」を付けている。
    print(f"焼きそば1人前は{yakisoba}円です。")

    # お小遣いから、焼きそばの金額を引く。
    #
    # pocket -= yakisoba は、
    # pocket = pocket - yakisoba
    # と同じ意味。
    #
    # 今回なら、
    # pocket = 2000 - 120
    # となり、pocket の中身は 1880 に更新される。
    #
    # ここで大切なのは、
    # 「pocket の値が新しい値に上書きされる」
    # という点。
    pocket -= yakisoba

    # 残りのお小遣いを表示する。
    #
    # 注意：
    # 単一責任の原則で考えると、
    # 本来この関数は「焼きそばを買って pocket を減らす」だけを担当し、
    # 表示は関数の外で行う方が設計としてはきれい。
    #
    # ただし、このWorkでは
    # 「関数の中で pocket を変更した結果、値が減っていること」
    # をすぐ確認する目的があるため、教材準拠としてここで表示している。
    print(f"残りのお小遣いは{pocket}円です。")


# yakisoba_shop 関数を呼び出す。
#
# 関数は、定義しただけでは実行されない。
# この行で初めて、
# ・焼きそばの値段表示
# ・pocket から 120円を引く
# ・残金表示
# が実行される。
yakisoba_shop()