# お小遣いの金額を覚えておく変数。
# pocket は「金額の数値」なので、2000 という整数で持っておく。
#
# ここで "2000円" のように文字列で持たないのは、
# あとで焼きそばを買って pocket から金額を引く処理につなげるため。
pocket = 2000

# f-string を使って、文章の中に pocket の値を埋め込む。
#
# {pocket} の部分には、現在の pocket の中身である 2000 が入る。
# 「円」は計算用の値ではなく、表示を分かりやすくするための文字。
#
# 出力：
# お小遣いは2000円です。
print(f"お小遣いは{pocket}円です。")