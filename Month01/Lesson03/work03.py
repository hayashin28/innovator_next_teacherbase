import time

def reply() -> str:
    # この関数は、かくれんぼの返事を表示するだけではなく、
    # ユーザーの入力結果を「外側の処理へ返す」役割を持っています。
    #
    # ここで返した ans は、count_up() を経由して、
    # 最終的に while True を止めるかどうかの判定材料になります。
    print('もういいかーい？')

    # ユーザーに yes / no を入力してもらいます。
    # 入力された文字列は、この場で完結せず、
    # 関数の戻り値として外側へ渡されます。
    ans = input('yes / no :')

    # yes の場合は「準備ができた」という意味として扱います。
    # ただし、ここでループを止めているわけではありません。
    # ループを止める判断は、さらに外側の while 側で行います。
    if ans == 'yes':
        print('もういいよ！')

    # no の場合は「まだ準備中」という意味として扱います。
    # この場合も ans を返すことで、外側が「続ける」と判断できます。
    elif ans == 'no':
        print('まーだだよ！')

    # 入力結果を呼び出し元へ返します。
    # この戻り値があるから、reply() の中だけで処理が閉じず、
    # 外側のループ制御とつながります。
    return ans


def count_up() -> str:
    # カウントする回数を変数として持たせています。
    # range(10) と直接書くよりも、
    # 「10回数える」という意味を num に持たせられます。
    num = 10

    # num 回だけ繰り返します。
    # i は 0 から始まるため、画面に表示するときだけ i + 1 にしています。
    for i in range(num):
        # 人間に見せたいカウントは 1 からなので、
        # 内部の 0 始まりの値を表示用に変換しています。
        print(i + 1)

        # 1秒待つことで、カウントを人間が認識できる速度にしています。
        time.sleep(1)

    # カウントが終わったあと、reply() に確認を任せます。
    #
    # 重要なのは、reply() の結果をここで受け取って終わりにせず、
    # count_up() の戻り値として、さらに外側へ返している点です。
    #
    # つまり count_up() は、
    # 「10秒数える処理」と「終了判定に使う入力結果」を接続する役割です。
    return reply()


# yes が返ってくるまで、同じ流れを繰り返します。
# このループ自体は常に続く形ですが、break によって明示的に抜けます。
while True:
    # count_up() は、10秒数えたあとに reply() を呼び、
    # reply() の戻り値をそのまま返します。
    #
    # そのため、ここでは reply() に直接触れていなくても、
    # ユーザーが入力した ans を使って終了判定ができます。
    if count_up() == 'yes':
        # yes が返ってきたときだけ、無限ループを終了します。
        # no の場合は break されないため、もう一度 count_up() から始まります。
        break